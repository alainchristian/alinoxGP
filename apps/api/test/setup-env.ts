import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

// Runs before any test module is imported. Tests use the ISOLATED test stack (infra/docker-compose.test.yml, compose
// project `gps-test`: PostgreSQL 54339, Redis 63809, Traccar 58092/55065) — never the development services.
// Start it with `pnpm test:infra:up` (`pnpm test` does it); wipe it completely with `pnpm test:reset`.
export const TEST_STACK = { postgresPort: 54339, redisPort: 63809, traccarRest: 'http://localhost:58092', traccarOsmand: 'http://localhost:55065' } as const;

const pg = (role: string, pw: string, db = 'gps_test') => `postgresql://${role}:${pw}@localhost:${TEST_STACK.postgresPort}/${db}`;
const defaults: Record<string, string> = {
  NODE_ENV: 'test',
  LOG_LEVEL: 'silent',
  APP_BASE_URL: 'http://localhost:5273',
  DATABASE_URL: pg('gps_app', 'gps_app_dev'),
  DATABASE_URL_SYSTEM: pg('gps_system', 'gps_system_dev'),
  DATABASE_URL_MIGRATE: pg('gps_owner', 'gps_owner_dev'),
  SHADOW_DATABASE_URL: pg('gps_owner', 'gps_owner_dev', 'gps_shadow'),
  REDIS_URL: `redis://localhost:${TEST_STACK.redisPort}/0`,
  JWT_ACCESS_SECRET: 'test-secret-test-secret-test-secret-test-secret',
  TOTP_ENCRYPTION_KEY: Buffer.alloc(32, 7).toString('base64'),
  THROTTLE_DEFAULT_LIMIT: '100000',
  THROTTLE_AUTH_LIMIT: '100000',
  // Background consumers are OFF by default so unrelated suites do not open engine connections.
  // The GPS end-to-end suites switch ingestion on explicitly.
  INGESTION_ENABLED: 'false',
  WORKERS_ENABLED: 'false',
  SIMULATOR_ENABLED: 'true',
  // A tracking notice is seeded, so acknowledgement would be demanded of every suite that registers a device. Off by default; the consent suite turns it on.
  DEVICE_CONSENT_REQUIRED: 'false',
  TRACCAR_URL: TEST_STACK.traccarRest,
  TRACCAR_OSMAND_URL: TEST_STACK.traccarOsmand,
};

// Traccar service-admin credentials of the TEST stack (random, generated by infra/scripts/test-stack.cjs). CI provides them
// through the environment. The development credentials in apps/api/.env are deliberately NOT read.
const envFile = join(__dirname, '..', '.env.test');
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = /^(TRACCAR_(?:USER|PASSWORD))=(.*)$/.exec(line);
    if (m?.[1]) process.env[m[1]] = m[2]; // the test stack's own credentials always win over an inherited development value
  }
}

// Infrastructure endpoints are FORCED to the test stack: an exported development DATABASE_URL / REDIS_URL / TRACCAR_URL in the
// developer's shell must never leak into a test run. (Everything else keeps `??=` so CI can still inject secrets.)
const FORCED = ['DATABASE_URL', 'DATABASE_URL_SYSTEM', 'DATABASE_URL_MIGRATE', 'SHADOW_DATABASE_URL', 'REDIS_URL', 'TRACCAR_URL', 'TRACCAR_OSMAND_URL'];
for (const [k, v] of Object.entries(defaults)) {
  if (FORCED.includes(k)) process.env[k] = v;
  else process.env[k] ??= v;
}

// Every test file (suite) gets its own Redis key namespace — which also gives it its own ingestion-lease name — so suites
// cannot read, overwrite or lock each other's keys, and a suite's leftovers are removed by key prefix when it closes.
// (Only inside a test file: in Jest's global setup the variable would leak into every worker and defeat the isolation.)
if (typeof jest !== 'undefined') process.env.REDIS_KEY_PREFIX ??= `t${randomBytes(4).toString('hex')}:`;
