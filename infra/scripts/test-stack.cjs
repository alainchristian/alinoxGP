// Manages the isolated TEST infrastructure (infra/docker-compose.test.yml).
//   node infra/scripts/test-stack.cjs up      start (if needed) and make sure the Traccar service admin exists
//   node infra/scripts/test-stack.cjs reset   destroy the volumes, start from scratch, bootstrap
//   node infra/scripts/test-stack.cjs down    stop and remove the containers (keeps volumes)
// The Traccar service admin credentials are random and written to apps/api/.env.test (git-ignored).
const { execFileSync } = require('node:child_process');
const { existsSync, readFileSync, writeFileSync } = require('node:fs');
const { randomBytes } = require('node:crypto');
const { join } = require('node:path');

const root = join(__dirname, '..', '..');
const compose = join(root, 'infra', 'docker-compose.test.yml');
const envFile = join(root, 'apps', 'api', '.env.test');
const TRACCAR = 'http://localhost:58092';
const ADMIN_EMAIL = 'gps-test-service@platform.local';

const dc = (...args) => execFileSync('docker', ['compose', '-f', compose, ...args], { stdio: 'inherit', cwd: root });

function readCreds() {
  if (!existsSync(envFile)) return null;
  const m = Object.fromEntries(readFileSync(envFile, 'utf8').split(/\r?\n/).map((l) => l.split(/=(.*)/s)).filter((p) => p[0]).map((p) => [p[0], p[1]]));
  return m.TRACCAR_USER && m.TRACCAR_PASSWORD ? { user: m.TRACCAR_USER, password: m.TRACCAR_PASSWORD } : null;
}

async function canLogin(user, password) {
  const res = await fetch(`${TRACCAR}/api/session`, {
    method: 'POST',
    headers: { 'content-type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({ email: user, password }),
  });
  return res.ok;
}

async function bootstrapAdmin() {
  const existing = readCreds();
  if (existing && (await canLogin(existing.user, existing.password))) return console.log('Traccar test admin: already set up');
  // On a fresh Traccar the first user created becomes the administrator (and registration then closes).
  const password = randomBytes(18).toString('base64url');
  const res = await fetch(`${TRACCAR}/api/users`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ name: 'GPS test service', email: ADMIN_EMAIL, password }),
  });
  if (!res.ok) throw new Error(`Could not create the Traccar test admin (HTTP ${res.status}). Run "pnpm test:reset" to rebuild the test stack from scratch.`);
  writeFileSync(envFile, `# Generated by infra/scripts/test-stack.cjs for the isolated TEST Traccar. Never commit.\nTRACCAR_USER=${ADMIN_EMAIL}\nTRACCAR_PASSWORD=${password}\n`);
  console.log(`Traccar test admin created; credentials written to ${envFile}`);
}

async function main() {
  const cmd = process.argv[2];
  if (cmd === 'down') return dc('down');
  if (cmd === 'reset') dc('down', '-v', '--remove-orphans');
  else if (cmd !== 'up') throw new Error('usage: test-stack.cjs up|reset|down');
  dc('up', '-d', '--wait');
  await bootstrapAdmin();
  console.log('Test stack ready: Postgres 54339, Redis 63809, Traccar 58092 (REST) / 55065 (OsmAnd)');
}

main().catch((e) => { console.error(String(e.message || e)); process.exit(1); });
